-- On-demand snapshots. No automatic freshness claim.
USE DATABASE IDENTIFIER($DEMO_DB);
USE SCHEMA CURATED;
USE WAREHOUSE IDENTIFIER($DEMO_WH);

CREATE DYNAMIC TABLE CURATED.PERFORMANCE_SUMMARY
  TARGET_LAG = DOWNSTREAM WAREHOUSE = __DEMO_WH__
  REFRESH_MODE = FULL INITIALIZE = ON_CREATE
AS
SELECT site.ID AS ENTITY_ID, site.NAME AS ENTITY_NAME,
       site.REGION, site.CATEGORY, site.STATUS,
       COUNT(*) AS EVENT_COUNT, SUM(o.OUTAGE_COUNT) AS OUTAGE_COUNT,
       SUM(o.OPERATING_HOURS) AS OPERATING_HOURS, SUM(o.PLANNED_HOURS) AS PLANNED_HOURS,
       SUM(o.DOWNTIME_HOURS) AS DOWNTIME_HOURS,
       SUM(o.INSPECTION_DUE) AS INSPECTION_DUE, SUM(o.INSPECTION_DONE) AS INSPECTION_DONE,
       SUM(o.GENERATION_MWH) AS GENERATION_MWH, SUM(o.AVOIDED_TCO2E) AS AVOIDED_TCO2E,
       SUM(o.INTERVALS_VALID) AS INTERVALS_VALID, SUM(o.METER_INTERVALS) AS METER_INTERVALS,
       SUM(o.GRIEVANCES) AS GRIEVANCES,
       100.0 * SUM(o.INTERVALS_VALID) / NULLIF(SUM(o.METER_INTERVALS), 0) AS METER_VALID_PCT,
       1000.0 * SUM(o.AVOIDED_TCO2E) / NULLIF(SUM(o.GENERATION_MWH), 0) AS KG_CO2E_PER_MWH,
       100.0 * SUM(o.OPERATING_HOURS) / NULLIF(SUM(o.PLANNED_HOURS), 0) AS AVAILABILITY_PCT,
       100.0 * SUM(o.INSPECTION_DONE) / NULLIF(SUM(o.INSPECTION_DUE), 0) AS INSPECTION_COMPLETION_PCT,
       MAX(o.EVENT_DATE) AS SOURCE_WATERMARK
FROM RAW.PLANT_DAILY o
JOIN RAW.PLANTS site ON site.ID = o.ENTITY_ID
GROUP BY site.ID, site.NAME, site.REGION, site.CATEGORY, site.STATUS;

CREATE DYNAMIC TABLE CURATED.TREND_ANALYSIS
  TARGET_LAG = DOWNSTREAM WAREHOUSE = __DEMO_WH__
  REFRESH_MODE = FULL INITIALIZE = ON_CREATE
AS
SELECT EVENT_DATE AS METRIC_DATE, COUNT(*) AS EVENT_COUNT,
       SUM(INTERVALS_VALID) AS INTERVALS_VALID, SUM(METER_INTERVALS) AS METER_INTERVALS,
       SUM(GENERATION_MWH) AS GENERATION_MWH, SUM(AVOIDED_TCO2E) AS AVOIDED_TCO2E,
       SUM(GRIEVANCES) AS GRIEVANCES, SUM(OUTAGE_COUNT) AS OUTAGE_COUNT,
       100.0 * SUM(INTERVALS_VALID) / NULLIF(SUM(METER_INTERVALS), 0) AS METER_VALID_PCT,
       1000.0 * SUM(AVOIDED_TCO2E) / NULLIF(SUM(GENERATION_MWH), 0) AS KG_CO2E_PER_MWH
FROM RAW.PLANT_DAILY
GROUP BY EVENT_DATE;

CREATE DYNAMIC TABLE CURATED.OUTAGE_CAUSES
  TARGET_LAG = DOWNSTREAM WAREHOUSE = __DEMO_WH__
  REFRESH_MODE = FULL INITIALIZE = ON_CREATE
AS
SELECT ROOT_CAUSE, SUM(OUTAGE_COUNT) AS OUTAGE_COUNT,
       SUM(DOWNTIME_HOURS) AS DOWNTIME_HOURS,
       SUM(METER_INTERVALS) - SUM(INTERVALS_VALID) AS INTERVALS_INVALID
FROM RAW.PLANT_DAILY
WHERE OUTAGE_COUNT > 0
GROUP BY ROOT_CAUSE;

CREATE DYNAMIC TABLE CURATED.KPI_SUMMARY
  TARGET_LAG = DOWNSTREAM WAREHOUSE = __DEMO_WH__
  REFRESH_MODE = FULL INITIALIZE = ON_CREATE
AS
WITH observations AS (
  SELECT SUM(INTERVALS_VALID) AS INTERVALS_VALID, SUM(METER_INTERVALS) AS METER_INTERVALS,
         SUM(GENERATION_MWH) AS GENERATION_MWH, SUM(AVOIDED_TCO2E) AS AVOIDED_TCO2E,
         SUM(GRIEVANCES) AS GRIEVANCES, SUM(OUTAGE_COUNT) AS OUTAGES,
         SUM(OPERATING_HOURS) AS OPERATING_HOURS, SUM(PLANNED_HOURS) AS PLANNED_HOURS,
         MAX(EVENT_DATE) AS SOURCE_WATERMARK
  FROM RAW.PLANT_DAILY
), sites AS (SELECT COUNT(*) AS SITE_COUNT FROM RAW.PLANTS),
defects AS (
  SELECT 100.0 * SUM(LEAST(DEFECTS_CLOSED, DEFECTS_FOUND)) / NULLIF(SUM(DEFECTS_FOUND), 0) AS DEFECT_CLOSURE_PCT
  FROM RAW.DEFECT_SURVEY
), metrics AS (
  SELECT 1 AS SORT_ORDER, 'Meter Data Valid' AS TITLE,
         100.0 * INTERVALS_VALID / NULLIF(METER_INTERVALS, 0) AS VALUE_NUM, '%' AS UNIT FROM observations
  UNION ALL SELECT 2, 'Generation Outages', OUTAGES, '' FROM observations
  UNION ALL SELECT 3, 'Total Generation', GENERATION_MWH / 1000.0, ' GWh' FROM observations
  UNION ALL SELECT 4, 'Estimated Avoided Emissions', AVOIDED_TCO2E / 1000.0, ' kt CO2e' FROM observations
  UNION ALL SELECT 5, 'Plant Availability', 100.0 * OPERATING_HOURS / NULLIF(PLANNED_HOURS, 0), '%' FROM observations
  UNION ALL SELECT 6, 'Plants Monitored', SITE_COUNT, '' FROM sites
  UNION ALL SELECT 7, 'Survey Defects Closed', DEFECT_CLOSURE_PCT, '%' FROM defects
  UNION ALL SELECT 8, 'Community Grievances', GRIEVANCES, '' FROM observations
)
SELECT metrics.SORT_ORDER, metrics.TITLE, metrics.VALUE_NUM,
       IFF(metrics.VALUE_NUM IS NULL, 'Unavailable',
           CASE WHEN metrics.UNIT = '' THEN TRIM(TO_VARCHAR(ROUND(metrics.VALUE_NUM), '999,999,999,990'))
                ELSE TRIM(TO_VARCHAR(ROUND(metrics.VALUE_NUM, 1), '999,990.0')) END || metrics.UNIT) AS DISPLAY,
       'neutral' AS STATUS, observations.SOURCE_WATERMARK
FROM metrics CROSS JOIN observations;

ALTER DYNAMIC TABLE CURATED.PERFORMANCE_SUMMARY SUSPEND;
ALTER DYNAMIC TABLE CURATED.TREND_ANALYSIS SUSPEND;
ALTER DYNAMIC TABLE CURATED.OUTAGE_CAUSES SUSPEND;
ALTER DYNAMIC TABLE CURATED.KPI_SUMMARY SUSPEND;
