-- Outage-risk scoring and avoided-emissions forecast over the synthetic snapshot.
-- Predicts P(forced generation outage in the next 7 days) per plant and reports
-- out-of-time holdout metrics; nothing is seeded as a prediction.
USE DATABASE IDENTIFIER($DEMO_DB);
USE WAREHOUSE IDENTIFIER($DEMO_WH);

CREATE VIEW ML.OUTAGE_FEATURES AS
SELECT r.ENTITY_ID, r.EVENT_DATE, t.CATEGORY, t.AGE_YEARS,
       r.EQUIP_TEMP_C, r.OUTPUT_PCT,
       AVG(r.EQUIP_TEMP_C) OVER (PARTITION BY r.ENTITY_ID ORDER BY r.EVENT_DATE ROWS BETWEEN 6 PRECEDING AND CURRENT ROW) AS TEMP_7D,
       SUM(r.OUTAGE_COUNT) OVER (PARTITION BY r.ENTITY_ID ORDER BY r.EVENT_DATE ROWS BETWEEN 29 PRECEDING AND CURRENT ROW) AS OUTAGES_30D,
       IFF(SUM(r.OUTAGE_COUNT) OVER (PARTITION BY r.ENTITY_ID ORDER BY r.EVENT_DATE ROWS BETWEEN 1 FOLLOWING AND 7 FOLLOWING) > 0,
           'OUTAGE', 'OK') AS LABEL,
       COUNT(*) OVER (PARTITION BY r.ENTITY_ID ORDER BY r.EVENT_DATE ROWS BETWEEN 1 FOLLOWING AND 7 FOLLOWING) AS FUTURE_DAYS
FROM RAW.PLANT_DAILY r JOIN RAW.PLANTS t ON t.ID = r.ENTITY_ID
-- Regional grid events are not plant-driven, so they are excluded from training.
WHERE r.ROOT_CAUSE NOT IN ('Storm grid disconnection', 'Transmission line trip') OR r.OUTAGE_COUNT = 0;

-- Time-based split: train on older labelled days, hold out the most recent 14 labelled days.
CREATE VIEW ML.OUTAGE_TRAIN AS
SELECT CATEGORY, AGE_YEARS, EQUIP_TEMP_C, OUTPUT_PCT, TEMP_7D, OUTAGES_30D, LABEL
FROM ML.OUTAGE_FEATURES
WHERE FUTURE_DAYS = 7 AND EVENT_DATE < DATEADD('day', -21, CURRENT_DATE());

CREATE VIEW ML.OUTAGE_HOLDOUT AS
SELECT ENTITY_ID, EVENT_DATE, CATEGORY, AGE_YEARS, EQUIP_TEMP_C, OUTPUT_PCT, TEMP_7D, OUTAGES_30D, LABEL
FROM ML.OUTAGE_FEATURES
WHERE FUTURE_DAYS = 7 AND EVENT_DATE >= DATEADD('day', -21, CURRENT_DATE());

CREATE SNOWFLAKE.ML.CLASSIFICATION ML.OUTAGE_RISK_MODEL(
  INPUT_DATA => TABLE(ML.OUTAGE_TRAIN),
  TARGET_COLNAME => 'LABEL'
);

-- Out-of-time holdout: precision/recall at 0.5 versus the base rate.
CREATE TABLE ML.OUTAGE_RISK_HOLDOUT_METRICS AS
WITH scored AS (
  SELECT LABEL, ML.OUTAGE_RISK_MODEL!PREDICT(INPUT_DATA => OBJECT_CONSTRUCT(
           'CATEGORY', CATEGORY, 'AGE_YEARS', AGE_YEARS, 'EQUIP_TEMP_C', EQUIP_TEMP_C,
           'OUTPUT_PCT', OUTPUT_PCT, 'TEMP_7D', TEMP_7D, 'OUTAGES_30D', OUTAGES_30D)):probability:OUTAGE::FLOAT AS P
  FROM ML.OUTAGE_HOLDOUT
)
SELECT COUNT(*) AS N,
       AVG(IFF(LABEL = 'OUTAGE', 1, 0)) AS BASE_RATE,
       SUM(IFF(P >= 0.5 AND LABEL = 'OUTAGE', 1, 0)) / NULLIF(SUM(IFF(P >= 0.5, 1, 0)), 0) AS PRECISION_AT_50,
       SUM(IFF(P >= 0.5 AND LABEL = 'OUTAGE', 1, 0)) / NULLIF(SUM(IFF(LABEL = 'OUTAGE', 1, 0)), 0) AS RECALL_AT_50,
       CURRENT_TIMESTAMP() AS EVALUATED_AT
FROM scored;

-- Latest-day score per plant (label unknown, so excluded from features).
CREATE TABLE ML.OUTAGE_RISK_SCORES AS
WITH latest AS (
  SELECT * FROM ML.OUTAGE_FEATURES
  QUALIFY ROW_NUMBER() OVER (PARTITION BY ENTITY_ID ORDER BY EVENT_DATE DESC) = 1
), scored AS (
  SELECT ENTITY_ID, EVENT_DATE,
         ML.OUTAGE_RISK_MODEL!PREDICT(INPUT_DATA => OBJECT_CONSTRUCT(
           'CATEGORY', CATEGORY, 'AGE_YEARS', AGE_YEARS, 'EQUIP_TEMP_C', EQUIP_TEMP_C,
           'OUTPUT_PCT', OUTPUT_PCT, 'TEMP_7D', TEMP_7D, 'OUTAGES_30D', OUTAGES_30D)) AS P
  FROM latest
)
SELECT ENTITY_ID, EVENT_DATE AS SCORED_AS_OF,
       ROUND(P:probability:OUTAGE::FLOAT, 4) AS OUTAGE_PROB_7D,
       CASE WHEN P:probability:OUTAGE::FLOAT >= 0.5 THEN 'High'
            WHEN P:probability:OUTAGE::FLOAT >= 0.25 THEN 'Medium' ELSE 'Low' END AS RISK_BAND,
       CURRENT_TIMESTAMP() AS SCORED_AT
FROM scored;

-- Portfolio-wide daily estimated avoided emissions forecast (14 days, t CO2e) from the daily series.
CREATE VIEW ML.DAILY_AVOIDED AS
SELECT EVENT_DATE::TIMESTAMP_NTZ AS TS, SUM(AVOIDED_TCO2E)::FLOAT AS AVOIDED_TCO2E
FROM RAW.PLANT_DAILY GROUP BY EVENT_DATE;

CREATE SNOWFLAKE.ML.FORECAST ML.AVOIDED_FORECAST_MODEL(
  INPUT_DATA => TABLE(ML.DAILY_AVOIDED),
  TIMESTAMP_COLNAME => 'TS',
  TARGET_COLNAME => 'AVOIDED_TCO2E'
);

CREATE TABLE ML.AVOIDED_FORECAST AS
SELECT TS::DATE AS FORECAST_DATE, ROUND(FORECAST) AS AVOIDED_TCO2E,
       ROUND(GREATEST(0, LOWER_BOUND)) AS LOWER_BOUND, ROUND(UPPER_BOUND) AS UPPER_BOUND
FROM TABLE(ML.AVOIDED_FORECAST_MODEL!FORECAST(FORECASTING_PERIODS => 14));
